_DEPT_RE = re.compile(r"(?:отдел[еа]?|подразделени[еи]|департамент[еа]?|служб[еа])\s*«?([^».,;\n]{3,40})", re.IGNORECASE)
_MGR_RE = re.compile(r"(?:руководител[ьяем]+|начальник[а-я]*|под руководством)\s+([А-ЯЁ][а-яё]+(?:\s[А-ЯЁ][а-яё]+)?)")


def find_entities(text: str) -> tuple[str, str]:
    """Отдел и руководитель, если названы явно. Ничего не угадываем."""
    d = _DEPT_RE.search(text)
    m = _MGR_RE.search(text)
    dept = d.group(1).strip() if d else ""
    if d and d.group(0).lower().startswith(("отдел", "подразделени", "департамент", "служб")):
        dept = d.group(0).strip(" «»")
    return dept, (m.group(1).strip() if m else "")


def analyze(source: str, utts: list[Utterance]) -> dict:
    emp = "\n".join(u.text for u in utts if u.speaker != "interviewer") or source
    dept, mgr = find_entities(emp)
    sentences = _sentences(emp)
    low = emp.lower()

    reason_scores = {r: sum(low.count(m) for m in ms) for r, ms in REASON_MARKERS.items()}
    reason = max(reason_scores, key=reason_scores.get) if any(reason_scores.values()) else "другое"
    reason_quote = next(iter(_pick(sentences[:3], REASON_MARKERS.get(reason, ()))), sentences[0] if sentences else "")

    pains = []
    for cat, markers in PAIN_MARKERS.items():
        hits = _pick(sentences, markers, skip_praise=True)
        if hits:
            pains.append({"label": cat, "category": cat, "mentions": len(hits), "quotes": hits[:3]})
    pains.sort(key=lambda p: -p["mentions"])
    pains = pains[:5]

    practices = []
    for cat, markers in PRACTICE_MARKERS.items():
        hits = _pick(sentences, markers)
        if hits:
            practices.append({"label": cat, "quote": hits[0]})
    practices = practices[:3]

    toxic = sum(1 for m in RISK_MARKERS if m in low)
    risk = "High" if toxic >= 1 else "Medium" if pains and pains[0]["mentions"] >= 2 else "Low"
    top = pains[0]["category"] if pains else ""
    return {
        "department": dept,
        "manager": mgr,
        "exit_reason": reason,
        "exit_reason_quote": reason_quote,
        "says": "; ".join(p["label"] for p in pains[:3]) or "жалоб не выделено",
        "feels": "оценка без модели: см. график настроения",
        "pain_points": pains,
        "best_practices": practices,
        "risk_zone": risk,
        "risk_rationale": "есть признаки, что уходить собираются и другие" if toxic else
                          "прямых признаков риска для команды в тексте нет",
        "improvement_suggestions": SUGGESTIONS.get(top, DEFAULT_SUGGESTIONS),
        "top_problem": top,
        "summary": f"Причина ухода: {reason}. Главная боль: {top or 'не выделена'}. Риск: {risk}.",
    }

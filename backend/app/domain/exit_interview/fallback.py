RISK_MARKERS = ("не один такой", "ещё двое", "половина отдела", "по собеседованиям", "думает так же",
                "будут уходить", "тоже уход")


def _sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if len(s.strip()) > 15]


_PRAISE = tuple(m for ms in PRACTICE_MARKERS.values() for m in ms)


def _pick(sentences: list[str], markers: tuple[str, ...], skip_praise: bool = False) -> list[str]:
    hits = []
    for s in sentences:
        low = s.lower()
        if skip_praise and any(m in low for m in _PRAISE):
            continue   # «руководитель всегда прикрывал» — это похвала, не боль
        if any(m in low for m in markers):
            hits.append(s)
    return hits



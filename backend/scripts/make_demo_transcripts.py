def make_transcript(rng: random.Random, scenario: str, plain: bool) -> str:
    s = SCENARIOS[scenario]
    pains = rng.sample(s["pains"], k=3)
    # главная боль повторяется дважды, чтобы частота упоминаний была видна
    main_cat, main_text = pains[0]
    repeat = {
        "процессы": "И опять про согласования: пока три отдела договорятся, задача уже никому не нужна.",
        "зарплата": "Про деньги повторюсь, потому что это главное: рынок ушёл, а мы стоим.",
        "карьера": "Ещё раз про рост: людям нужно понимать, куда они идут, а не просто «работай дальше».",
        "руководство": "И это снова про руководителя: без нормального диалога с ним ничего не изменится.",
        "команда": "Про команду добавлю: пока конфликт не разрулят, будут уходить и другие.",
        "коммуникация": "Коммуникация — это отдельная боль, повторю: решения надо доносить до людей.",
        "нагрузка": "Про переработки скажу ещё раз: так долго не живут.",
        "сроки": "Сроки, опять сроки. Никто не считает, сколько это стоит людям.",
        "инструменты": "Инструменты повторю отдельно: ручная работа съедает половину дня.",
    }[main_cat]
    practices = rng.sample(PRACTICES, k=2)
    toxic = rng.random() < 0.35

    dept_i = DEPT_BY_SCENARIO[scenario] if rng.random() < 0.7 else rng.randrange(len(DEPARTMENTS))
    mgr_i = dept_i if rng.random() < 0.8 else rng.randrange(len(MANAGERS))
    answers = [
        f"Работал в подразделении «{DEPARTMENTS[dept_i]}», под руководством {MANAGERS[mgr_i]}.",
        rng.choice(s["reason"]) + " " + main_text,
        pains[1][1] + " " + pains[2][1],
        repeat + (" " + rng.choice(TOXIC) if toxic else ""),
        practices[0][1] + " " + practices[1][1],
        rng.choice(RETURN[scenario]),
        rng.choice(ADVICE),
    ]
    if plain:
        return " ".join(f"...{q} {a}" for q, a in zip(QUESTIONS, answers))
    return "\n".join(f"Интервьюер: {q}\nСотрудник: {a}\n" for q, a in zip(QUESTIONS, answers))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--count", type=int, default=12)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)
    # распределение причин намеренно неровное: как в жизни, деньги и карьера чаще
    plan = ["деньги", "карьера", "деньги", "микроклимат", "карьера", "нереализованность",
            "деньги", "карьера", "микроклимат", "деньги", "карьера", "нереализованность"]
    for i in range(args.count):
        scenario = plan[i % len(plan)]
        text = make_transcript(rng, scenario, plain=(i % 4 == 3))
        (out / f"interview_{i + 1:02d}.txt").write_text(text, encoding="utf-8")
    print(f"Создано {args.count} транскриптов в {out}")


if __name__ == "__main__":
    main()
